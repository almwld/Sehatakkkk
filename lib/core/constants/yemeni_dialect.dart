  // ✅ تحويل النص الفصيح إلى لهجة يمنية
  static String toYemeniDialect(String text) {
    String result = text;
    for (var entry in sanaaniWords.entries) {
      if (result.contains(entry.key)) {
        result = result.replaceAll(entry.key, entry.value);
      }
    }
    return result;
  }

  // ✅ إضافة كلمات يمنية عشوائية
  static String addYemeniFlavor(String text) {
    final List<String> flavors = [
      'والله',
      'يا خوي',
      'يا غالي',
      'يا طيب',
      'هذا واجبنا',
      'الله يخليك',
      'تبارك الله',
      'ما شاء الله',
      'الحمد لله',
      'الله كريم',
      'على بركة الله',
      'إن شاء الله',
      'ما عليه',
      'زين والله',
      'طيب يا باشا',
    ];

    final random = DateTime.now().millisecondsSinceEpoch % flavors.length;
    final flavor = flavors[random];
    
    // إضافة كلمة يمنية في نهاية الجملة
    if (text.length > 10) {
      return '$text، $flavor';
    }
    return text;
  }

