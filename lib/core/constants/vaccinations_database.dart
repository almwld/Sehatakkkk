  static List<String> getVaccinations(String age) {
    return vaccinations[age] ?? [];
  }

  static List<String> getAgeGroups() {
    return vaccinations.keys.toList();
  }

  static String getNextVaccination(DateTime birthDate) {
    final now = DateTime.now();
    final ageMonths = (now.year - birthDate.year) * 12 + now.month - birthDate.month;
    final ageYears = ageMonths ~/ 12;

    if (ageYears >= 18) return 'الكبار';
    if (ageYears >= 16) return '16-18 سنة';
    if (ageYears >= 11) return '11-12 سنة';
    if (ageYears >= 4) return '4-6 سنوات';
    if (ageMonths >= 18) return '18 شهر';
    if (ageMonths >= 15) return '15 شهر';
    if (ageMonths >= 12) return '12 شهر';
    if (ageMonths >= 9) return '9 أشهر';
    if (ageMonths >= 6) return '6 أشهر';
    if (ageMonths >= 4) return '4 أشهر';
    if (ageMonths >= 2) return 'شهرين';
    return 'الولادة';
  }
