  static IconData getFileIcon(String extension) {
    final ext = extension.toLowerCase();
    if (['jpg', 'jpeg', 'png', 'gif', 'webp', 'svg'].contains(ext)) {
      return fileImage;
    } else if (['mp4', 'mov', 'avi', 'mkv', 'webm'].contains(ext)) {
      return fileVideo;
    } else if (['mp3', 'wav', 'm4a', 'aac', 'ogg'].contains(ext)) {
      return fileAudio;
    } else if (['pdf'].contains(ext)) {
      return filePDF;
    } else if (['doc', 'docx'].contains(ext)) {
      return fileWord;
    } else if (['xls', 'xlsx'].contains(ext)) {
      return fileExcel;
    } else if (['ppt', 'pptx'].contains(ext)) {
      return filePowerPoint;
    } else if (['zip', 'rar', '7z', 'tar', 'gz'].contains(ext)) {
      return fileArchive;
    } else {
      return fileDocument;
    }
  }

  static IconData getReactionIcon(String emoji) {
    switch (emoji) {
      case '👍':
        return like;
      case '👎':
        return dislike;
      case '❤️':
        return heart;
      case '🔥':
        return fire;
      case '😂':
        return laugh;
      case '😮':
        return wow;
      case '😢':
        return cry;
      case '🙏':
        return pray;
      default:
        return heart;
    }
  }

  static IconData getStatusIcon(String status) {
    switch (status.toLowerCase()) {
      case 'online':
        return Icons.circle;
      case 'offline':
        return Icons.circle_outlined;
      case 'busy':
        return Icons.do_not_disturb;
      case 'away':
        return Icons.access_time;
      default:
        return Icons.circle_outlined;
    }
