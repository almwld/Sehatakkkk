  // ✅ الحصول على معلومات عن دواء محدد
  String getMedicineInfo(String medicineName) {
    final lowerName = medicineName.toLowerCase();
    for (final entry in _knowledgeBase.entries) {
      if (entry.key.toLowerCase() == lowerName) {
        return entry.value['response'] as String;
      }
    }
    return '💊 لم أجد معلومات عن هذا الدواء. يرجى التحقق من الاسم أو استشارة طبيبك.';
  }

  // ✅ تحليل الأعراض
  String analyzeSymptoms(String symptoms) {
    final lowerSymptoms = symptoms.toLowerCase();
    if (lowerSymptoms.contains('حمى') || lowerSymptoms.contains('حرارة')) {
      return '🩺 قد تكون هذه أعراض التهاب أو عدوى. ننصح بمراجعة الطبيب إذا استمرت الأعراض.';
    }
    if (lowerSymptoms.contains('سعال') || lowerSymptoms.contains('كحة')) {
      return '🩺 السعال قد يكون بسبب حساسية أو التهاب في الجهاز التنفسي. اشرب سوائل دافئة واستشر طبيبك.';
    }
    return '🩺 شكراً لمشاركتك الأعراض. ننصح بمراجعة الطبيب للحصول على تشخيص دقيق.';
  }

